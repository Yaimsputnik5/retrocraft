package com.sammwy.retrocraft;

/** Original NROM test program: cycles the backdrop palette every vblank and emits a pulse tone. */
final class HomebrewRom {
    static byte[] bytes() {
        byte[] rom = new byte[16 + 16384 + 8192];
        rom[0] = 'N'; rom[1] = 'E'; rom[2] = 'S'; rom[3] = 0x1a;
        rom[4] = 1; rom[5] = 1;
        int[] code = {
            0x78, 0xd8, 0xa2, 0xff, 0x9a, 0xe8, // SEI, CLD, stack
            0x8e, 0x00, 0x20, 0x8e, 0x01, 0x20, // disable rendering/NMI
            0x86, 0x00, // zero counter
            0xa9, 0x01, 0x8d, 0x15, 0x40, // pulse enable
            0xa9, 0xbf, 0x8d, 0x00, 0x40,
            0xa9, 0xfd, 0x8d, 0x02, 0x40,
            0xa9, 0x08, 0x8d, 0x03, 0x40,
            // $8022: wait for vblank, write universal backdrop from incrementing counter
            0x2c, 0x02, 0x20, 0x10, 0xfb,
            0xa9, 0x3f, 0x8d, 0x06, 0x20,
            0xa9, 0x00, 0x8d, 0x06, 0x20,
            0xa5, 0x00, 0x29, 0x3f, 0x8d, 0x07, 0x20,
            0xe6, 0x00,
            0x4c, 0x22, 0x80
        };
        for (int i = 0; i < code.length; i++) rom[16 + i] = (byte) code[i];
        for (int i = 0x3ffa; i < 0x4000; i += 2) { rom[16 + i] = 0; rom[16 + i + 1] = (byte) 0x80; }
        return rom;
    }
}
